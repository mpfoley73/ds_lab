# R/analysis.R
# Simple data analysis script

# Load required packages
library(ggplot2)

# Generate sample data
set.seed(123)
df <- data.frame(
  x = rnorm(100),
  y = rnorm(100),
  group = sample(c("A", "B"), 100, replace = TRUE)
)

# Create a plot
p <- ggplot(df, aes(x = x, y = y, color = group)) +
  geom_point() +
  labs(title = "Sample Scatter Plot",
       x = "X Variable",
       y = "Y Variable") +
  theme_minimal()

# Save the plot
ggsave("R/plot.png", p, width = 6, height = 4)

# Print summary
summary(df)

# snapshot currently used packages to renv.lock
renv::snapshot()
```

Explanation: restore a project from renv.lock (e.g., on a new machine or CI).
```r
# restore packages exactly as in renv.lock
renv::restore()
```

Notes:
- Commit renv.lock (and your DESCRIPTION if using a package) to Git.
- Do not commit the renv/library/ directory; let renv restore in CI/peers.

# Python: venv and poetry (two common approaches)

Minimal: venv + pip + requirements.txt.

Explanation: create and use a venv, then install and pin.
```bash
# create virtual environment (POSIX)
python3 -m venv .venv
source .venv/bin/activate

# install and pin
pip install -r requirements.txt   # or pip install numpy pandas
pip freeze > requirements.txt
```

Poetry (higher-level, lockfile-based):
```bash
# initialize poetry (interactive)
poetry init

# add packages and create poetry.lock
poetry add pandas numpy

# reproduce elsewhere
poetry install
```

# Using Python from R (reticulate)

Explanation: create/use a Python venv and tell reticulate to use it.
```r
# from R: create virtualenv (optional) and point reticulate to it
reticulate::virtualenv_create(".venv")
reticulate::use_virtualenv(".venv", required = TRUE)

# inspect Python configuration
reticulate::py_config()
```

Tip: keep separate venvs per project (.venv or env/) and commit only the lockfile/requirements.

# Lockfiles and reproducibility

- renv.lock pins R package versions and sources.
- requirements.txt pins Python versions (pip freeze style) but consider pip-tools or poetry for more deterministic resolution.
- Commit lockfiles and use CI to validate restoration.

