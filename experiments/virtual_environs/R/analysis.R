# Optional: GitHub Actions CI (R + Python basic restore + run)

Explanation: basic CI that restores renv and Python venv, then runs small checks.

Save as .github/workflows/ci.yml
# yaml
```{text}
name: R+Python CI

on: [push, pull_request]

jobs:
  build:
    runs-on: ubuntu-latest
    strategy:
      matrix:
        r: [4.3]
        python: [3.10]
    steps:
      - uses: actions/checkout@v4

      - name: Setup R
        uses: r-lib/actions/setup-r@v2
        with:
          r-version: ${{ matrix.r }}

      - name: Restore renv
        run: |
          R -e 'install.packages("renv", repos="https://cloud.r-project.org")'
          R -e 'renv::restore()'

      - name: Setup Python
        uses: actions/setup-python@v4
        with:
          python-version: ${{ matrix.python }}

      - name: Install Python deps
        run: |
          python -m venv .venv
          source .venv/bin/activate
          pip install -r python/requirements.txt

      - name: Run R script
        run: Rscript R/analysis.R

      - name: Run Python script
        run: |
          source .venv/bin/activate
          python python/app.py
```

# Deploying to Posit Cloud (simple, non-automated)

Two simple options:

1) Quick: push your repo to GitHub, then in Posit Cloud create "New Project from Git" and provide the repository URL. Posit Cloud will import and (depending on project type) run a rendering/build step. Ensure renv.lock and requirements.txt are present.

2) For Posit Connect (server) or scripted deploys: use rsconnect package or a deployment workflow for your target. That is a separate topic — for demos, the Git import above is simplest.

